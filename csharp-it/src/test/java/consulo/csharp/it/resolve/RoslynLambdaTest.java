/**
 * The semantic model tests of lambdas from Roslyn (LambdaTests, LambdaDiscardParametersTests,
 * SimpleLambdaParametersWithModifiersTests), generated by {@code roslyn/lambda/generate.py}: the source of the test
 * with a marker comment before every node it asserts on.
 * <ul>
 * <li>{@code /*@type:T*}{@code /expr} - the type of the expression; for {@code x.Member} the type of {@code x}</li>
 * <li>{@code /*@symbol:S*}{@code /ref} - what the reference resolves to: {@code Type name} for a variable,
 * {@code Owner.Name(Types)} for a method</li>
 * <li>{@code /*@lambda:(T, ...)*}{@code /} - the parameter types of the lambda which follows</li>
 * </ul>
 *
 * @author VISTALL
 */
@ExtendWith(HeadlessProjectExtension.class)
public class RoslynLambdaTest
{
	private static final Pattern MARKER = Pattern.compile("/\\*@(type|symbol|lambda):(.*)\\*/");

	private static final int TYPE_FLAGS = CSharpTypeRefPresentationUtil.QUALIFIED_NAME;

	static Stream<Arguments> sources() throws Exception
	{
		List<String> files;
		try(Stream<Path> list = Files.list(CSharpResolveTesting.resource("roslyn/lambda")))
		{
			files = list.map(path -> path.getFileName().toString()).filter(name -> name.endsWith(".cs")).sorted().toList();
		}

		List<Arguments> arguments = new ArrayList<>();
		for(String file : files)
		{
			for(MockSdk sdk : MockSdk.values())
			{
				arguments.add(Arguments.of(file, sdk));
			}
		}
		return arguments.stream();
	}

	@ParameterizedTest(name = "{0} {1}")
	@MethodSource("sources")
	public void lambda(String fileName, MockSdk sdk, HeadlessProjects projects) throws Exception
	{
		String source = Files.readString(CSharpResolveTesting.resource("roslyn/lambda/" + fileName), StandardCharsets.UTF_8);

		PsiFile file = CSharpResolveTesting.openSource(projects, sdk, fileName, source, sdk.getLinqLibraries());

		List<String> expected = new ArrayList<>();
		List<String> actual = ReadAction.compute(() ->
		{
			List<String> result = new ArrayList<>();
			for(PsiComment comment : PsiTreeUtil.findChildrenOfType(file, PsiComment.class))
			{
				Matcher matcher = MARKER.matcher(comment.getText());
				if(!matcher.matches())
				{
					continue;
				}

				String kind = matcher.group(1);
				PsiElement leaf = PsiTreeUtil.nextVisibleLeaf(comment);
				String at = kind + " at " + (leaf == null ? "<end>" : "'" + leaf.getText() + "'@" + leaf.getTextOffset()) + ": ";

				expected.add(at + matcher.group(2));
				result.add(at + evaluate(kind, leaf));
			}
			return result;
		});

		assertThat(actual).as("markers in %s", fileName).isNotEmpty();
		assertThat(String.join("\n", actual)).as("%s on %s", fileName, sdk).isEqualTo(String.join("\n", expected));
	}

	@RequiredReadAction
	private static String evaluate(String kind, PsiElement leaf)
	{
		if(leaf == null)
		{
			return "no element";
		}

		switch(kind)
		{
			case "type":
			{
				DotNetExpression expression = expressionAt(leaf, false);
				return expression == null ? "no expression" : type(expression.toTypeRef(true));
			}
			case "symbol":
			{
				DotNetExpression expression = expressionAt(leaf, true);
				if(!(expression instanceof CSharpReferenceExpression reference))
				{
					return "no reference";
				}
				return symbol(reference.resolve());
			}
			case "lambda":
			{
				CSharpLambdaExpressionImpl lambda = PsiTreeUtil.getParentOfType(leaf, CSharpLambdaExpressionImpl.class, false);
				if(lambda == null)
				{
					return "no lambda";
				}
				StringJoiner parameters = new StringJoiner(", ", "(", ")");
				for(CSharpLambdaParameter parameter : lambda.getParameters())
				{
					parameters.add(type(parameter.toTypeRef(true)));
				}
				return parameters.toString();
			}
			default:
				throw new IllegalArgumentException(kind);
		}
	}

	/**
	 * The largest expression which starts at {@code leaf}. A qualifier stays itself - the type of {@code x} in
	 * {@code x.ToString()} - unless {@code throughQualifiers}, which goes up to the member a reference names
	 * ({@code c.Add}); an incomplete member access ({@code a.}) is never entered.
	 */
	@RequiredReadAction
	private static DotNetExpression expressionAt(PsiElement leaf, boolean throughQualifiers)
	{
		DotNetExpression expression = PsiTreeUtil.getParentOfType(leaf, DotNetExpression.class, false);
		if(expression == null || expression.getTextRange().getStartOffset() != leaf.getTextRange().getStartOffset())
		{
			return null;
		}

		while(expression.getParent() instanceof DotNetExpression parent && parent.getTextRange().getStartOffset() == expression.getTextRange().getStartOffset())
		{
			if(parent instanceof CSharpReferenceExpression parentReference && parentReference.getQualifier() == expression)
			{
				if(!throughQualifiers || parentReference.getReferenceElement() == null)
				{
					break;
				}
			}
			else if(throughQualifiers)
			{
				break;
			}
			expression = parent;
		}
		return expression;
	}

	@RequiredReadAction
	private static String symbol(PsiElement element)
	{
		if(element == null)
		{
			return "null";
		}
		if(element instanceof DotNetVariable variable)
		{
			return type(variable.toTypeRef(true)) + " " + variable.getName();
		}
		if(element instanceof DotNetLikeMethodDeclaration method)
		{
			StringJoiner parameters = new StringJoiner(", ", "(", ")");
			for(DotNetTypeRef parameterTypeRef : method.getParameterTypeRefs())
			{
				parameters.add(type(parameterTypeRef));
			}
			PsiElement parent = method.getParent();
			String owner = parent instanceof DotNetQualifiedElement qualified ? qualified.getPresentableQName() : "?";
			return owner + "." + method.getName() + parameters;
		}
		return element.getClass().getSimpleName();
	}

	@RequiredReadAction
	private static String type(DotNetTypeRef typeRef)
	{
		return CSharpTypeRefPresentationUtil.buildText(typeRef, TYPE_FLAGS);
	}
}
