/**
 * Roslyn tests which run a program whose output tells which overload each call bound to - every overload prints a literal
 * of its own - generated by {@code roslyn/overloadOutput/generate.py} with the expected output on the first line.
 * <p>
 * Nothing runs: {@code Main} is walked in evaluation order (arguments before the call, lambda bodies not at all), every
 * call is resolved, the body of a resolved method of the test source is walked the same way - a constructor with its
 * field initializers and the constructor it calls, a delegate with the method of the method group converted to it - and
 * {@code Console.Write} contributes its literal. The trace must be the expected output, whitespace aside.
 *
 * @author VISTALL
 */
@ExtendWith(HeadlessProjectExtension.class)
public class RoslynOverloadOutputTest
{
	private static final String EXPECTED_OUTPUT = "// expectedOutput: ";

	private static final int MAX_DEPTH = 8;

	/**
	 * Roslyn behavior not supported - skipped, not failed, until it is
	 */
	private static final Map<String, String> UNSUPPORTED = Map.of(
			"BetterCandidates_TestInstanceReceiver09.cs", "query expressions are not bound to Select/Where/... calls",
			"OverloadResolution_TestRefMethodGroup.cs", "new D(ref M) - the legacy ref/out modifier in a delegate creation is not supported"
	);

	static Stream<Arguments> sources() throws Exception
	{
		List<String> files;
		try(Stream<Path> list = Files.list(CSharpResolveTesting.resource("roslyn/overloadOutput")))
		{
			files = list.map(path -> path.getFileName().toString()).filter(name -> name.endsWith(".cs")).sorted().toList();
		}

		List<Arguments> arguments = new ArrayList<>();
		for(String file : files)
		{
			for(MockSdk sdk : MockSdk.values())
			{
				arguments.add(Arguments.of(file, sdk));
			}
		}
		return arguments.stream();
	}

	@ParameterizedTest(name = "{0} {1}")
	@MethodSource("sources")
	public void output(String fileName, MockSdk sdk, HeadlessProjects projects) throws Exception
	{
		String unsupported = UNSUPPORTED.get(fileName);
		Assumptions.assumeTrue(unsupported == null, unsupported);

		String source = Files.readString(CSharpResolveTesting.resource("roslyn/overloadOutput/" + fileName), StandardCharsets.UTF_8);
		assertThat(source).startsWith(EXPECTED_OUTPUT);
		String expected = source.substring(EXPECTED_OUTPUT.length(), source.indexOf('\n')).replace("\\n", "\n");

		PsiFile file = CSharpResolveTesting.openSource(projects, sdk, fileName, source, sdk.getLinqLibraries());

		StringBuilder log = new StringBuilder();
		String actual = ReadAction.compute(() ->
		{
			DotNetLikeMethodDeclaration main = PsiTreeUtil.findChildrenOfType(file, DotNetLikeMethodDeclaration.class).stream()
					.filter(method -> "Main".equals(method.getName()))
					.findFirst()
					.orElseThrow(() -> new AssertionError("no Main in " + fileName));

			Interpreter interpreter = new Interpreter(file, log);
			interpreter.run(body(main), 0);
			return interpreter.myOutput.toString();
		});

		assertThat(withoutWhitespace(actual)).as("%s on %s, trace:%n%s%ncalls:%n%s", fileName, sdk, actual, log).isEqualTo(withoutWhitespace(expected));
	}

	/**
	 * Walks code in evaluation order and appends what the calls in it print. Values are tracked for delegates only: a
	 * variable or a parameter holds the method of the method group converted to it.
	 */
	private static class Interpreter
	{
		private final PsiFile myFile;
		private final StringBuilder myLog;
		private final StringBuilder myOutput = new StringBuilder();
		private final Map<PsiElement, DotNetLikeMethodDeclaration> myDelegates = new HashMap<>();

		private Interpreter(PsiFile file, StringBuilder log)
		{
			myFile = file;
			myLog = log;
		}

		@RequiredReadAction
		private void run(PsiElement element, int depth)
		{
			if(element == null || depth > MAX_DEPTH)
			{
				return;
			}

			List<PsiElement> afterCall = new ArrayList<>();
			for(PsiElement child = element.getFirstChild(); child != null; child = child.getNextSibling())
			{
				// declared here, not run here
				if(child instanceof CSharpLambdaExpressionImpl || child instanceof CSharpDelegateExpressionImpl
						|| child instanceof DotNetLikeMethodDeclaration || child instanceof DotNetTypeDeclaration)
				{
					continue;
				}
				// an object or collection initializer runs after the constructor
				if(element instanceof CSharpNewExpression && (child instanceof CSharpArrayInitializerImpl || child instanceof CSharpFieldOrPropertySetBlock))
				{
					afterCall.add(child);
					continue;
				}
				run(child, depth);
			}

			if(element instanceof CSharpCallArgumentListOwner call)
			{
				call(call, depth);
			}

			for(PsiElement child : afterCall)
			{
				run(child, depth);
			}

			if(element instanceof DotNetVariable variable && !(element instanceof DotNetParameter) && variable.getInitializer() != null)
			{
				bind(variable, variable.getInitializer());
			}
			else if(element instanceof CSharpAssignmentExpressionImpl assignment
					&& assignment.getLeftExpression() instanceof CSharpReferenceExpression left
					&& left.resolve() instanceof DotNetVariable variable)
			{
				bind(variable, assignment.getRightExpression());
			}
		}

		@RequiredReadAction
		private void call(CSharpCallArgumentListOwner call, int depth)
		{
			PsiElement callable = call.resolveToCallable();
			myLog.append(call.getText().replaceAll("\\s+", " ")).append(" -> ").append(describe(callable)).append(candidates(call)).append('\n');

			if(callable instanceof DotNetVariable variable)
			{
				// a delegate invoked
				DotNetLikeMethodDeclaration target = myDelegates.get(variable);
				if(target != null)
				{
					runMethod(target, depth);
				}
				return;
			}

			if(callable == null && call instanceof CSharpNewExpression newExpression
					&& newExpression.toTypeRef(false).resolve().getElement() instanceof DotNetTypeDeclaration type)
			{
				// the default constructor
				if(type.getContainingFile() == myFile)
				{
					runFieldInitializers(type, depth);
				}
				return;
			}

			if(!(callable instanceof DotNetLikeMethodDeclaration method))
			{
				if(callable == null)
				{
					myOutput.append("<unresolved ").append(call.getText()).append(">");
				}
				return;
			}

			if(isConsoleWrite(method))
			{
				for(CSharpCallArgument argument : call.getCallArguments())
				{
					myOutput.append(literal(argument.getArgumentExpression()));
				}
				if("WriteLine".equals(method.getName()))
				{
					myOutput.append('\n');
				}
				return;
			}

			// new D(M) - the delegate is the method group
			if(method instanceof CSharpMethodDeclaration delegate && delegate.isDelegate())
			{
				return;
			}

			bindParameters(call, method);
			runMethod(method, depth);
		}

		@RequiredReadAction
		private void runMethod(DotNetLikeMethodDeclaration method, int depth)
		{
			method = implementation(method);
			if(method.getContainingFile() != myFile)
			{
				return;
			}

			if(method instanceof CSharpConstructorDeclaration constructor)
			{
				CSharpConstructorSuperCall superCall = constructor.getConstructorSuperCall();
				// this(...) runs the field initializers in the constructor it calls
				if((superCall == null || superCall.getExpression().kind() != CSharpReferenceExpression.ResolveToKind.THIS)
						&& constructor.getParent() instanceof DotNetTypeDeclaration type)
				{
					runFieldInitializers(type, depth + 1);
				}
				if(superCall != null)
				{
					run(superCall, depth + 1);
				}
			}
			run(body(method), depth + 1);
		}

		@RequiredReadAction
		private void runFieldInitializers(DotNetTypeDeclaration type, int depth)
		{
			for(DotNetNamedElement member : type.getMembers())
			{
				if(member instanceof DotNetFieldDeclaration field && !field.hasModifier(DotNetModifier.STATIC) && field.getInitializer() != null)
				{
					run(field, depth);
				}
			}
		}

		/**
		 * A method without a body - of an interface, abstract - runs the one implementation of it in the file.
		 */
		@RequiredReadAction
		private DotNetLikeMethodDeclaration implementation(DotNetLikeMethodDeclaration method)
		{
			if(body(method) != null || !(method.getParent() instanceof DotNetTypeDeclaration owner) || owner.getVmQName() == null)
			{
				return method;
			}

			List<DotNetLikeMethodDeclaration> implementations = new ArrayList<>();
			for(DotNetTypeDeclaration type : PsiTreeUtil.findChildrenOfType(myFile, DotNetTypeDeclaration.class))
			{
				if(type == owner || !type.isInheritor(owner.getVmQName(), true))
				{
					continue;
				}
				for(DotNetNamedElement member : type.getMembers())
				{
					if(member instanceof DotNetLikeMethodDeclaration candidate && body(candidate) != null
							&& CSharpElementCompareUtil.isEqual(candidate, method, CSharpElementCompareUtil.CHECK_RETURN_TYPE))
					{
						implementations.add(candidate);
					}
				}
			}
			return implementations.size() == 1 ? implementations.get(0) : method;
		}

		@RequiredReadAction
		private void bindParameters(CSharpCallArgumentListOwner call, DotNetLikeMethodDeclaration method)
		{
			DotNetParameter[] parameters = method.getParameters();
			CSharpCallArgument[] arguments = call.getCallArguments();
			for(int i = 0; i < arguments.length; i++)
			{
				DotNetParameter parameter = null;
				if(arguments[i] instanceof CSharpNamedCallArgument named)
				{
					for(DotNetParameter candidate : parameters)
					{
						if(candidate.getName() != null && candidate.getName().equals(named.getName()))
						{
							parameter = candidate;
						}
					}
				}
				else if(i < parameters.length)
				{
					parameter = parameters[i];
				}

				if(parameter != null)
				{
					bind(parameter, arguments[i].getArgumentExpression());
				}
			}
		}

		@RequiredReadAction
		private void bind(DotNetVariable variable, DotNetExpression value)
		{
			DotNetLikeMethodDeclaration method = delegateValue(value);
			if(method != null)
			{
				myDelegates.put(variable, method);
			}
		}

		/**
		 * The method a delegate value calls - for a method group, new D(methodGroup) and a variable holding one.
		 */
		@RequiredReadAction
		private DotNetLikeMethodDeclaration delegateValue(DotNetExpression expression)
		{
			if(expression instanceof CSharpParenthesesExpressionImpl parentheses)
			{
				return delegateValue(parentheses.getInnerExpression());
			}
			if(expression instanceof CSharpOutRefWrapExpressionImpl wrap)
			{
				return delegateValue(wrap.getInnerExpression());
			}
			if(expression instanceof CSharpNewExpression newExpression)
			{
				CSharpCallArgument[] arguments = newExpression.getCallArguments();
				return arguments.length == 1 ? delegateValue(arguments[0].getArgumentExpression()) : null;
			}
			if(expression instanceof CSharpReferenceExpression reference)
			{
				PsiElement resolved = reference.resolve();
				if(resolved instanceof DotNetLikeMethodDeclaration method)
				{
					myLog.append("method group ").append(reference.getText()).append(" -> ").append(describe(method)).append('\n');
					return method;
				}
				if(resolved instanceof DotNetVariable variable)
				{
					return myDelegates.get(variable);
				}
			}
			return null;
		}

		@RequiredReadAction
		private static String describe(PsiElement element)
		{
			if(element == null)
			{
				return "null";
			}
			if(element instanceof DotNetLikeMethodDeclaration method)
			{
				PsiElement navigation = element.getNavigationElement();
				String text = navigation.getText();
				if(text == null)
				{
					StringJoiner parameters = new StringJoiner(", ", "(", ")");
					for(DotNetTypeRef parameterTypeRef : method.getParameterTypeRefs())
					{
						parameters.add(CSharpTypeRefPresentationUtil.buildText(parameterTypeRef, CSharpTypeRefPresentationUtil.QUALIFIED_NAME));
					}
					return method.getName() + parameters;
				}
				int brace = text.indexOf('{');
				text = (brace > 0 ? text.substring(0, brace) : text).replaceAll("\\s+", " ").strip();
				return text + " @" + navigation.getTextOffset();
			}
			return element.getClass().getSimpleName() + " " + element.getText();
		}

		@RequiredReadAction
		private static String candidates(CSharpCallArgumentListOwner call)
		{
			StringJoiner joiner = new StringJoiner(", ", " [", "]");
			for(ResolveResult result : call.multiResolve(true))
			{
				String weight = result instanceof MethodResolveResult methodResult ? String.valueOf(methodResult.getCalcResult().getWeight()) : "?";
				joiner.add((result.isValidResult() ? "" : "!") + weight + " " + describe(result.getElement()));
			}
			return joiner.toString();
		}
	}

	@RequiredReadAction
	private static PsiElement body(DotNetLikeMethodDeclaration method)
	{
		return method instanceof DotNetCodeBlockOwner owner ? owner.getCodeBlock().getElement() : null;
	}

	@RequiredReadAction
	private static boolean isConsoleWrite(DotNetLikeMethodDeclaration method)
	{
		String name = method.getName();
		if(!"Write".equals(name) && !"WriteLine".equals(name))
		{
			return false;
		}
		PsiElement parent = method.getParent();
		return parent instanceof DotNetTypeDeclaration type && "System.Console".equals(type.getVmQName())
				|| parent instanceof DotNetNamedElement named && "Console".equals(named.getName());
	}

	/**
	 * What Console.Write prints for a literal - the generator takes literal arguments only.
	 */
	@RequiredReadAction
	private static String literal(DotNetExpression expression)
	{
		if(expression == null)
		{
			return "";
		}
		String text = expression.getText().strip();
		if(text.startsWith("\"") && text.endsWith("\"") || text.startsWith("'") && text.endsWith("'"))
		{
			return text.substring(1, text.length() - 1).replace("\\n", "\n").replace("\\\"", "\"").replace("\\\\", "\\");
		}
		if("true".equals(text) || "false".equals(text))
		{
			return Character.toUpperCase(text.charAt(0)) + text.substring(1);
		}
		String number = text.replaceAll("[a-zA-Z]+$", "");
		if(number.contains("."))
		{
			double value = Double.parseDouble(number);
			return value == Math.rint(value) ? String.valueOf((long) value) : number;
		}
		return number;
	}

	private static String withoutWhitespace(String text)
	{
		return text.replaceAll("\\s+", "");
	}
}
