/**
 * The "Color Color" tests of Roslyn (ColorColorTests - a simple name which is both a member and the name of its type,
 * C# spec 12.8.7.2), generated by {@code roslyn/colorColor/generate.py}: the source of the test with the
 * {@code /*<bind>*}{@code /X/*</bind>*}{@code /} of Roslyn replaced by marker comments.
 * <ul>
 * <li>{@code /*@symbol:S*}{@code /ref} - the reference right after the marker resolves to {@code S}</li>
 * <li>{@code ref/*@parent:S*}{@code /.Member} - the member access whose qualifier is the reference right before the
 * marker ({@code ref.Member}) resolves to {@code S}</li>
 * </ul>
 * The symbol {@code S} is {@code <Kind> <signature>}, the types with C# keywords for the predefined types
 * ({@code int}, not {@code System.Int32}):
 * <ul>
 * <li>{@code Type <qualified name>} - a type, a delegate, or an alias (as the type it names)</li>
 * <li>{@code Field|Property|Event <type> <Owner>.<Name>}</li>
 * <li>{@code Parameter|Local <type> <name>}</li>
 * <li>{@code Method <return type> <Owner>.<Name><T, ...>(<modifiers> <type> <name>, ...)} - the modifiers are
 * {@code this params ref out in}, the declaration (not a constructed generic method or a reduced extension method)</li>
 * </ul>
 *
 * @author VISTALL
 */
@ExtendWith(HeadlessProjectExtension.class)
public class RoslynColorColorTest
{
	private static final Pattern MARKER = Pattern.compile("/\\*@(symbol|parent):(.*)\\*/");

	private static final int TYPE_FLAGS = CSharpTypeRefPresentationUtil.QUALIFIED_NAME | CSharpTypeRefPresentationUtil.FORCE_TYPE_KEYWORD;

	private static final CSharpModifier[] PARAMETER_MODIFIERS = {
			CSharpModifier.THIS,
			CSharpModifier.PARAMS,
			CSharpModifier.REF,
			CSharpModifier.OUT,
			CSharpModifier.IN
	};

	static Stream<Arguments> sources() throws Exception
	{
		List<String> files;
		try(Stream<Path> list = Files.list(CSharpResolveTesting.resource("roslyn/colorColor")))
		{
			files = list.map(path -> path.getFileName().toString()).filter(name -> name.endsWith(".cs")).sorted().toList();
		}

		List<Arguments> arguments = new ArrayList<>();
		for(String file : files)
		{
			for(MockSdk sdk : MockSdk.values())
			{
				arguments.add(Arguments.of(file, sdk));
			}
		}
		return arguments.stream();
	}

	@ParameterizedTest(name = "{0} {1}")
	@MethodSource("sources")
	public void colorColor(String fileName, MockSdk sdk, HeadlessProjects projects) throws Exception
	{
		String source = Files.readString(CSharpResolveTesting.resource("roslyn/colorColor/" + fileName), StandardCharsets.UTF_8);

		PsiFile file = CSharpResolveTesting.openSource(projects, sdk, fileName, source, sdk.getLinqLibraries());

		List<String> expected = new ArrayList<>();
		List<String> actual = ReadAction.compute(() ->
		{
			List<String> result = new ArrayList<>();
			for(PsiComment comment : PsiTreeUtil.findChildrenOfType(file, PsiComment.class))
			{
				Matcher matcher = MARKER.matcher(comment.getText());
				if(!matcher.matches())
				{
					continue;
				}

				String kind = matcher.group(1);
				PsiElement leaf = kind.equals("symbol") ? PsiTreeUtil.nextVisibleLeaf(comment) : PsiTreeUtil.prevVisibleLeaf(comment);
				String at = kind + " at " + (leaf == null ? "<none>" : "'" + leaf.getText() + "'@" + leaf.getTextOffset()) + ": ";

				expected.add(at + matcher.group(2));
				result.add(at + evaluate(kind, leaf));
			}
			return result;
		});

		assertThat(actual).as("markers in %s", fileName).isNotEmpty();
		assertThat(String.join("\n", actual)).as("%s on %s", fileName, sdk).isEqualTo(String.join("\n", expected));
	}

	@RequiredReadAction
	private static String evaluate(String kind, PsiElement leaf)
	{
		if(leaf == null)
		{
			return "no element";
		}

		// the simple name the leaf is: no qualifier, the leaf is its name
		CSharpReferenceExpression reference = PsiTreeUtil.getParentOfType(leaf, CSharpReferenceExpression.class, false);
		PsiElement name = reference == null ? null : reference.getReferenceElement();
		if(reference == null || reference.getQualifier() != null || name == null || !name.getTextRange().equals(leaf.getTextRange()))
		{
			return "no simple name reference";
		}

		switch(kind)
		{
			case "symbol":
				return symbol(reference.resolve());
			case "parent":
				if(reference.getParent() instanceof CSharpReferenceExpression memberAccess && memberAccess.getQualifier() == reference)
				{
					return symbol(memberAccess.resolve());
				}
				return "no member access";
			default:
				throw new IllegalArgumentException(kind);
		}
	}

	@RequiredReadAction
	private static String symbol(PsiElement element)
	{
		if(element == null)
		{
			return "null";
		}
		if(element instanceof CSharpTypeDefStatement alias)
		{
			PsiElement target = alias.toTypeRef().resolve().getElement();
			return target == null ? "Alias " + alias.getName() : symbol(target);
		}
		if(element instanceof CSharpMethodDeclaration method && method.isDelegate())
		{
			return "Type " + method.getPresentableQName();
		}
		if(element instanceof DotNetTypeDeclaration type)
		{
			return "Type " + type.getPresentableQName();
		}
		if(element instanceof DotNetLikeMethodDeclaration method)
		{
			// e.M(1) resolves to the extension method as an instance one - show its declaration, as Roslyn's reduced form does
			if(CSharpMethodImplUtil.isExtensionWrapper(element) && element.getUserData(CSharpResolveUtil.EXTENSION_METHOD_WRAPPER) instanceof DotNetLikeMethodDeclaration declaration)
			{
				method = declaration;
			}
			// E.M<int>(1) resolves to M<T> with T filled in - show the declaration
			if(method.getOriginalElement() instanceof DotNetLikeMethodDeclaration original && original != method)
			{
				method = original;
			}
			return "Method " + method(method);
		}
		if(element instanceof DotNetFieldDeclaration field)
		{
			return "Field " + type(field.toTypeRef(true)) + " " + member(field);
		}
		if(element instanceof DotNetPropertyDeclaration property)
		{
			return "Property " + type(property.toTypeRef(true)) + " " + member(property);
		}
		if(element instanceof DotNetEventDeclaration event)
		{
			return "Event " + type(event.toTypeRef(true)) + " " + member(event);
		}
		if(element instanceof DotNetParameter || element instanceof CSharpLambdaParameter)
		{
			DotNetVariable parameter = (DotNetVariable) element;
			return "Parameter " + type(parameter.toTypeRef(true)) + " " + parameter.getName();
		}
		if(element instanceof DotNetLocalVariable local)
		{
			return "Local " + type(local.toTypeRef(true)) + " " + local.getName();
		}
		return element.getClass().getSimpleName();
	}

	@RequiredReadAction
	private static String method(DotNetLikeMethodDeclaration method)
	{
		StringBuilder builder = new StringBuilder();
		builder.append(type(method.getReturnTypeRef())).append(" ").append(member(method));

		DotNetGenericParameter[] genericParameters = method.getGenericParameters();
		if(genericParameters.length > 0)
		{
			StringJoiner joiner = new StringJoiner(", ", "<", ">");
			for(DotNetGenericParameter genericParameter : genericParameters)
			{
				joiner.add(genericParameter.getName());
			}
			builder.append(joiner);
		}

		StringJoiner parameters = new StringJoiner(", ", "(", ")");
		for(DotNetParameter parameter : method.getParameters())
		{
			StringBuilder text = new StringBuilder();
			for(CSharpModifier modifier : PARAMETER_MODIFIERS)
			{
				if(parameter.hasModifier(modifier))
				{
					text.append(modifier.name().toLowerCase(Locale.ROOT)).append(" ");
				}
			}
			text.append(type(parameter.toTypeRef(true))).append(" ").append(parameter.getName());
			parameters.add(text);
		}
		builder.append(parameters);
		return builder.toString();
	}

	/**
	 * {@code Owner.Name} - the owner is the qualified name of the type the member is declared in.
	 */
	@RequiredReadAction
	private static String member(DotNetQualifiedElement element)
	{
		PsiElement parent = element.getParent();
		String owner = parent instanceof DotNetQualifiedElement qualified ? qualified.getPresentableQName() : element.getPresentableParentQName();
		return (owner == null || owner.isEmpty() ? "" : owner + ".") + element.getName();
	}

	@RequiredReadAction
	private static String type(DotNetTypeRef typeRef)
	{
		return CSharpTypeRefPresentationUtil.buildText(typeRef, TYPE_FLAGS | CSharpTypeRefPresentationUtil.NO_REF);
	}
}
