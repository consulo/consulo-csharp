package consulo.csharp.impl.ide.highlight.check.impl;

import consulo.annotation.access.RequiredReadAction;
import consulo.csharp.impl.ide.highlight.CSharpHighlightContext;
import consulo.csharp.impl.ide.highlight.check.CompilerCheck;
import consulo.csharp.module.extension.CSharpLanguageVersion;
import consulo.dotnet.psi.DotNetLikeMethodDeclaration;

import java.util.List;

/**
 * Inconsistent accessibility: parameter type is less accessible than indexer; see {@link CS0050}
 *
 * @author VISTALL
 */
public class CS0055 extends CompilerCheck<DotNetLikeMethodDeclaration> {
    @RequiredReadAction
    @Override
    public List<? extends HighlightInfoFactory> check(CSharpLanguageVersion languageVersion, CSharpHighlightContext highlightContext, DotNetLikeMethodDeclaration element) {
        return CS0050.parameterTypes(this, element, CS0050.Kind.INDEXER);
    }
}
